"""What COSA does on the hard instances, and which mitigation is why -- §12.4's study.

#36. §12.4 (``paper.tex:936``) asks that the robustness families exist "to identify failure
modes **before** optimizing performance", and §14 asks that the answer be checkable rather
than asserted. This module runs the study: every family, every mitigation, on and off, with
the outcome recorded either way.

**A study is code, not prose, and this is why.** The narrative belongs in
``docs/development/failure-modes.md`` and it is written from what :func:`study` returns. Any
number in that document can be regenerated by running this, which is Success Criterion 6's
real content -- "COSA's numerical behaviour on degenerate and ill-conditioned problems is
understood" is a claim that decays the moment it is written down by hand.

**Mitigations are measured by removing them, one at a time.** §12.4 asks "which M7
mitigation addressed which failure, with before/after evidence", and the only honest way to
get that is a counterfactual: solve the same instance with the mitigation disabled and see
what happens. :data:`MITIGATIONS` names the four that can be switched off through the public
:func:`cosa.solve` signature, and :func:`ablate` runs them. Two more -- #29's anti-cycling
guard and #23's Lagrangian curvature -- are not switchable and are covered by their own
tests instead, which is recorded here rather than quietly omitted.

**A failure is classified, not merely reported.** :class:`Outcome` distinguishes four
things that a status string alone runs together: an answer that is optimal and certified, an
answer that is optimal but whose certificate is loose, a *diagnosed* stop -- ``degenerate``,
``stalled``, ``blocked-at-apex``, each of which names a specific thing that happened -- and
an undiagnosed one, which is the iteration limit. Only the last is a failure in the sense
§12.4 is worried about, and keeping them apart is most of what the study is for.
"""

