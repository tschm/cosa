"""Every generated family, structured and robustness alike, in one place.

§12.4's six robustness families are what the issue asks about, and the structured ones are
here too because "which mitigation addressed which failure" is only meaningful next to
instances that never needed one. A study of only the hard cases cannot tell a mitigation
that fixed something from a mitigation that is always on.
"""


@dataclass(frozen=True)
class Policy:
    """How to solve, so that a mitigation can be switched without a keyword splat.

    Named rather than a ``dict`` of keywords, because the three switches are of three
    different kinds -- a numerical parameter, a boolean policy, and a transformation applied
    before the solver sees the problem -- and a mapping of ``str`` to ``object`` loses that
    and cannot be type-checked besides.

    Attributes:
        regularization: §8.3's ``delta``. Zero disables the fallback.
        reuse: whether #27's factorization cache is used.
        scale: whether §13.3's Ruiz equilibration is applied before solving.
    """

    regularization: float = REGULARIZATION
    reuse: bool = True
    scale: bool = False


AS_SHIPPED: Final = Policy()
"""The solver's own defaults, which is what every mitigation is measured against."""

MITIGATIONS: Final[Mapping[str, tuple[Policy, Policy]]] = {
    "§8.3 regularization": (AS_SHIPPED, Policy(regularization=0.0)),
    "§13.2 factorization reuse": (AS_SHIPPED, Policy(reuse=False)),
    "§13.3 Ruiz equilibration": (Policy(scale=True), AS_SHIPPED),
}
"""Each M7 mitigation as the pair of policies that turn it on and off.

A pair rather than a single "disabled" keyword, because the three are not all defaulted the
same way. §8.3's regularization and §13.2's reuse are on by default and the ablation removes
them; §13.3's equilibration is *off* by default -- it is a transformation of the problem
rather than a policy of the solver, and whether to apply it is a decision the caller makes --
so its ablation adds it. Writing both sides makes that asymmetry visible instead of encoding
it in which dictionary is empty.

Short, and the shortness is a finding of its own. Most of what protects this solver is not
optional: #23's Lagrangian curvature, #29's anti-cycling guard and no-progress rule, #18's
exact conic step and #20's retraction are all unconditional, because a solver with them
switched off is not a worse solver but a different one -- it does not converge, and an
ablation that always reports "iteration limit" measures nothing. Those have their own
before-and-after tests where each landed. What is ablated here is what can honestly be
called a *policy*.
"""


@dataclass(frozen=True, eq=False)
class Outcome:
    """What happened on one instance, classified rather than merely reported.

    Attributes:
        family: the family's name.
        status: :attr:`cosa.solver.cosa.Solution.status`.
        residual: the largest of §6's five residuals at termination.
        iterations: how many the solve took.
        factorizations: how many fresh factorizations it needed.
        revisits: the most times any one working set was returned to. Above #29's threshold
            means the solve was cycling; one means it never backtracked.
        certified: whether the residuals put the answer inside §6's tolerance.
        gap: the relative difference between COSA's objective and the reference solver's, or
            ``None`` when no reference was available. ``None`` is *not* agreement, which is
            why :attr:`verdict` reports it as ``unchecked`` rather than as ``solved``.
        supplied_start: whether the solver had to be handed a feasible point because it
            could not construct one. A property of the *formulation* -- a cone head that is
            not a free variable -- rather than of the solve, and separated from the verdict
            for that reason.
        exhausted: whether the solve used its entire iteration budget. Kept apart from the
            verdict because the two can both be true: a solve that runs to the limit and
            *arrives* is reported ``optimal``, since :func:`cosa.solver.cosa._finish`
            recovers the multipliers and lets the residuals have the last word. That is the
            right answer and it is also a warning, so it is recorded rather than rounded
            into one or the other.
    """

    family: str
    status: str
    residual: float
    iterations: int
    factorizations: int
    revisits: int
    certified: bool
    gap: float | None = None
    supplied_start: bool = False
    exhausted: bool = False

    @property
    def verdict(self) -> str:
        """One of five words, which is the classification the study exists to make.

        The order of the tests matters. Disagreement with a reference outranks a clean
        certificate, because a certificate that certifies the wrong answer is worse than no
        certificate: it is the one failure mode a study of this kind cannot catch by looking
        harder at its own numbers, and it is the mode ``badly scaled`` was in for two waves.
        """
        if self.status != "optimal":
            return "undiagnosed" if self.status == "iteration_limit" else "diagnosed"
        if self.gap is None:
            return "unchecked"
        if self.gap > OBJECTIVE_TOLERANCE:
            return "wrong"
        return "solved" if self.certified else "loose"

    def __str__(self) -> str:
        """One table row."""
        against = "  no reference" if self.gap is None else f"  gap {self.gap:8.1e}"
        note = "  (start supplied)" if self.supplied_start else ""
        note += "  (used the whole budget)" if self.exhausted else ""
        return (
            f"{self.family:22s} {self.verdict:11s} {self.status:16s} "
            f"residual {self.residual:8.1e}{against}  {self.iterations:5d} iters  "
            f"{self.factorizations:4d} fact  {self.revisits:3d} revisits{note}"
        )


@dataclass(frozen=True, eq=False)
class Ablation:
    """One mitigation switched off, and what it cost.

    Attributes:
        mitigation: which one.
        family: the instance it was measured on.
        with_it: the outcome with the mitigation in place.
        without_it: the outcome without it.
    """

    mitigation: str
    family: str
    with_it: Outcome
    without_it: Outcome

    @property
    def mattered(self) -> bool:
        """Did removing it change the verdict, or cost more than a tenth of the iterations?

        Two ways for a mitigation to matter, and they are not the same. Changing the verdict
        is the strong form -- the instance solves with it and does not without. Costing
        iterations is the weak form, and worth reporting separately: a mitigation that never
        changes an outcome but halves the work is still doing something, and one that does
        neither is not earning its place.
        """
        if self.with_it.verdict != self.without_it.verdict:
            return True
        return self.without_it.iterations > 1.1 * max(1, self.with_it.iterations)

    def __str__(self) -> str:
        """One line saying whether it mattered and by how much."""
        change = f"{self.without_it.verdict} -> {self.with_it.verdict}"
        return (
            f"{self.mitigation:28s} {self.family:20s} without/with: {change:26s} "
            f"{self.without_it.iterations:5d} -> {self.with_it.iterations:5d} iters"
        )


def _run(instance: PortfolioInstance, policy: Policy = AS_SHIPPED) -> tuple[Solution, bool]:
    """Solve an instance, falling back to its own witness when no start can be constructed.

    **No family reaches the fallback any more, and how that changed is the study's best
    finding.** ``turnover`` and ``badly scaled`` used to, because
    :func:`cosa.solver.initialization.raise_free_heads` refused any cone head row whose
    coefficient was not exactly one -- so conic feasibility could not be repaired, the elastic
    Phase I had nowhere to start, and the study had to hand in the family's own witness. Removing
    that restriction removed the need. The fallback is kept because it is the honest response for
    a *general* SOCP whose head really is constrained elsewhere, and because a study meant to be
    pointed at new families should not crash on the first one that is shaped differently.

    Every family carries a :attr:`cosa.experiments.portfolio.PortfolioInstance.witness`, and
    handing the solver one is what a caller with a portfolio in hand would do -- so taking that
    route is recorded, not hidden, and is not counted as a failure of the algorithm.

    Args:
            instance: the instance to solve.
            policy: which mitigations to apply. ``scale`` puts the solve entirely in the
                equilibrated problem, which :meth:`cosa.linear_algebra.scaling.Scaling.apply`
                licenses: the feasible sets correspond, the objectives differ by a positive
                factor, and the multipliers map back under a positive diagonal.

    Returns:
            The solution, and whether a start had to be supplied.
    """
    problem, witness = instance.problem, instance.witness
    if policy.scale:
        factors = equilibrate(problem)
        problem, witness = factors.apply(problem), factors.scale_point(witness)
    try:
        return solver.solve(problem, regularization=policy.regularization, reuse=policy.reuse), False
    except (NeedsPhaseOneError, ProblemError):  # pragma: no cover - no family reaches this any more
        return (
            solver.solve(problem, start=witness, regularization=policy.regularization, reuse=policy.reuse),
            True,
        )


def _reference_gap(problem: SOCP, objective: float, oracle: ReferenceSolver | None) -> float | None:
    """How far ``objective`` is from a reference solver's, relatively.

    Args:
        problem: the instance.
        objective: COSA's objective there.
        oracle: the reference solver, or ``None``.

    Returns:
        The relative gap, or ``None`` when no reference could answer -- which the verdict
        reports as ``unchecked`` rather than silently as agreement.
    """
    if oracle is None:
        return None
    try:
        return relative_gap(objective, oracle.solve(problem).objective)
    except SolverUnavailableError:
        return None


def _outcome(
    name: str,
    solution: Solution,
    *,
    supplied: bool = False,
    gap: float | None = None,
    limit: int = MAX_ITERATIONS,
    tolerance: float = TOLERANCE,
) -> Outcome:
    """Classify one solve.

    Args:
        name: the family's name.
        solution: what the solver returned.
        supplied: whether a feasible start had to be handed in.
        gap: the relative objective gap against a reference solver, or ``None``.
        limit: the iteration budget the solve was given.
        tolerance: §6's tolerance for the certificate.

    Returns:
        The outcome.
    """
    return Outcome(
        family=name,
        gap=gap,
        supplied_start=supplied,
        exhausted=solution.metrics.iterations >= limit,
        status=solution.status,
        residual=float(solution.residuals.largest),
        iterations=solution.metrics.iterations,
        factorizations=solution.metrics.factorizations,
        revisits=solution.metrics.working_set_revisits,
        certified=bool(solution.residuals.is_optimal(tolerance=tolerance)),
    )


def study(
    assets: int = 20,
    *,
    seeds: Sequence[int] = (0, 1, 2),
    families: Mapping[str, Callable[..., PortfolioInstance]] = FAMILIES,
    oracle: ReferenceSolver | bool | None = True,
) -> tuple[Outcome, ...]:
    """Solve every family at every seed and classify what happened.

    §12.4's first two items -- "result per family" and "behaviour at the apex and on
    rank-deficient ``Sigma``" -- in one pass. The apex and the rank deficiency are not
    special-cased: ``large`` and ``factor exposure`` build a rank-``k`` covariance over many
    more assets, so ``L`` has a large null space, the minimum-risk portfolio has risk exactly
    zero, and ``lam > 0`` takes it. Their outcomes *are* the apex behaviour.

    Args:
        assets: how many assets each instance has. Twenty rather than the eight the other
            studies use, because ``large`` builds a rank-``k`` covariance with ``k`` fixed at
            ten and refuses an instance it cannot make low-rank.
        seeds: which seeds to draw.
        families: which families to study, defaulting to all of them. A subset is a
            legitimate thing to ask for -- someone debugging one family wants exactly that,
            and so does a test that needs the study to be *cheap* rather than exhaustive.
            Note that ``large`` is what forces ``assets`` to twenty; a subset without it can
            use a much smaller instance.
        oracle: the reference solver every answer is checked against. ``True`` picks one,
            ``False`` skips the check, and a solver may be passed directly. Skipping it does
            not produce a ``solved`` verdict -- it produces ``unchecked``, because "nothing
            disagreed with me" and "a reference agreed with me" are different claims and
            conflating them is what let a wrong answer read as solved for two waves.

    Returns:
        One outcome per family and seed, in family order.
    """
    checker = _oracle(oracle)
    outcomes = []
    for name, build in families.items():
        for seed in seeds:
            instance = build(assets, seed=seed)
            solution, supplied = _run(instance)
            outcomes.append(
                _outcome(
                    name,
                    solution,
                    supplied=supplied,
                    gap=_reference_gap(instance.problem, solution.objective(instance.problem), checker),
                )
            )
    return tuple(outcomes)


def _checked(
    name: str,
    instance: PortfolioInstance,
    policy: Policy,
    oracle: ReferenceSolver | None,
) -> Outcome:
    """Solve under one policy and classify the result against the reference.

    Args:
        name: the family's name.
        instance: the instance.
        policy: which mitigations to apply.
        oracle: the reference solver, or ``None``.

    Returns:
        The outcome.
    """
    solution, supplied = _run(instance, policy)
    problem = equilibrate(instance.problem).apply(instance.problem) if policy.scale else instance.problem
    # The objective is compared in the *original* problem's terms whether or not the solve
    # happened in a scaled one: `Scaling.apply` multiplies the objective by a positive
    # factor, so a scaled objective is not comparable with an unscaled reference's.
    objective = solution.objective(problem)
    return _outcome(name, solution, supplied=supplied, gap=_reference_gap(problem, objective, oracle))


def _oracle(oracle: ReferenceSolver | bool | None) -> ReferenceSolver | None:
    """Resolve the ``oracle`` argument into a solver or ``None``.

    Args:
        oracle: ``True`` to pick one, ``False`` or ``None`` for none, or a solver.

    Returns:
        The solver, or ``None`` when the check is skipped or nothing is installed.
    """
    if oracle is True:
        try:
            return default_solver()
        except SolverUnavailableError:
            return None
    return None if oracle is False else oracle


def ablate(
    assets: int = 20,
    *,
    seed: int = 0,
    families: Mapping[str, Callable[..., PortfolioInstance]] = FAMILIES,
    oracle: ReferenceSolver | bool | None = True,
) -> tuple[Ablation, ...]:
    """§12.4's fourth item: which mitigation addressed which failure, by removing it.

    Args:
        assets: how many assets each instance has.
        seed: which draw to measure on. One rather than several, because an ablation is a
            controlled comparison and averaging it over seeds hides the instances where the
            mitigation is the difference between an answer and none.
        families: which families to ablate over, defaulting to all of them.
        oracle: the reference solver both sides are checked against. Both sides, because a
            mitigation that turns a ``wrong`` answer into a ``solved`` one is the strongest
            thing an ablation can find and comparing two unchecked verdicts would miss it.

    Returns:
        One ablation per mitigation and family.
    """
    checker = _oracle(oracle)
    results = []
    for mitigation, (on, off) in MITIGATIONS.items():
        for name, build in families.items():
            instance = build(assets, seed=seed)
            results.append(
                Ablation(
                    mitigation=mitigation,
                    family=name,
                    with_it=_checked(name, instance, on, checker),
                    without_it=_checked(name, instance, off, checker),
                )
            )
    return tuple(results)


def report(
    assets: int = 20,
    *,
    seeds: Sequence[int] = (0, 1, 2),
    families: Mapping[str, Callable[..., PortfolioInstance]] = FAMILIES,
    oracle: ReferenceSolver | bool | None = True,
) -> str:
    """The whole study as text, for a document or a terminal.

    Args:
        assets: how many assets each instance has.
        seeds: which seeds to draw for the per-family half.
        families: which families to study, defaulting to all of them.
        oracle: the reference solver every answer is checked against.

    Returns:
        A report: every outcome, then every ablation that mattered, then the tally.
    """
    outcomes = study(assets, seeds=seeds, families=families, oracle=oracle)
    lines = [f"failure-mode study: {len(families)} families, {len(seeds)} seed(s), {assets} assets", ""]
    lines += [str(outcome) for outcome in outcomes]
    tally: dict[str, int] = {}
    for outcome in outcomes:
        tally[outcome.verdict] = tally.get(outcome.verdict, 0) + 1
    lines += ["", "verdicts: " + ", ".join(f"{count} {verdict}" for verdict, count in sorted(tally.items()))]
    disagreeing = wrong(outcomes)
    if disagreeing:
        lines += ["", "DISAGREES WITH THE REFERENCE (a certificate certifying the wrong answer):"]
        lines += [f"  {outcome}" for outcome in disagreeing]
    lines.append("")
    lines += ["ablations that mattered:"]
    mattered = [ablation for ablation in ablate(assets, seed=seeds[0], families=families) if ablation.mattered]
    lines += [str(ablation) for ablation in mattered] or ["  none"]
    return "\n".join(lines)


def wrong(outcomes: Sequence[Outcome]) -> tuple[Outcome, ...]:
    """The outcomes whose objective disagrees with the reference despite a clean certificate.

    The category the study exists to surface. A ``diagnosed`` stop is honest and an
    ``undiagnosed`` one is at least visible; this one looks like success.

    Args:
        outcomes: what :func:`study` returned.

    Returns:
        The disagreeing ones.
    """
    return tuple(outcome for outcome in outcomes if outcome.verdict == "wrong")


def undiagnosed(outcomes: Sequence[Outcome]) -> tuple[Outcome, ...]:
    """The outcomes that stopped without naming a reason.

    The only ones §12.4 counts as unresolved failures. A ``degenerate``, ``stalled`` or
    ``blocked-at-apex`` stop is documented behaviour with an issue behind it; an iteration
    limit is the solver saying it does not know.

    Args:
        outcomes: what :func:`study` returned.

    Returns:
        The undiagnosed ones.
    """
    return tuple(outcome for outcome in outcomes if outcome.verdict == "undiagnosed")


def cycling(outcomes: Sequence[Outcome], *, threshold: int) -> tuple[Outcome, ...]:
    """The outcomes whose working set was returned to more often than #29 allows.

    Args:
        outcomes: what :func:`study` returned.
        threshold: :data:`cosa.solver.anticycling.REVISITS`.

    Returns:
        The cycling ones, which should be none.
    """
    return tuple(outcome for outcome in outcomes if outcome.revisits > threshold)
